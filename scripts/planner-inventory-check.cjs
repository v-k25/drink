  const sizeA = b1.sizeMl, sizeB = twoBrands.find(p => p.sizeMl !== sizeA).sizeMl
  const sizeFiltered = sizes => twoBrands.filter(p => sizes.includes(p.sizeMl))
  // Search is global (name, brand or category across the whole catalogue) and has its own filter scope.
  const searchHits = text => catalogue.filter(p => `${p.name} ${p.brand} ${p.category}`.toLowerCase().includes(text.toLowerCase()))
  for (const width of [1440, 390]) {
    await page.setViewportSize({ width, height: 844 })
    await chooseCategory('Beer')
    await expectMatches(beer)
    assert.equal(await page.getByRole('button', { name: 'Clear all filters', exact: true }).count(), 0)
    await openFilters()
    assert.ok(await filters.locator('button[aria-pressed]').evaluateAll(chips => chips.every(el => { const r = el.getBoundingClientRect(); return r.height >= 44 && r.width >= 44 })), 'filter chips are at least 44px')
    assert.equal(await filters.getByRole('group', { name: 'Brand', exact: true }).getByRole('button').count(), new Set(beer.map(p => p.brand)).size)
    assert.equal(await filters.getByRole('group', { name: 'Pack size', exact: true }).getByRole('button').count(), new Set(beer.map(p => p.sizeMl)).size)
    await brandChip(b1.brand).focus(); await page.keyboard.press('Space')
    assert.equal(await brandChip(b1.brand).getAttribute('aria-pressed'), 'true')
    await closeFilters()
    await expectMatches(beer.filter(p => p.brand === b1.brand))
    await openFilters(); await sizeChip(sizeA).click(); await closeFilters()
    await expectMatches(beer.filter(p => p.brand === b1.brand && p.sizeMl === sizeA))
    await openFilters(); await brandChip(b0.brand).click(); await closeFilters()
    await expectMatches(sizeFiltered([sizeA]))
    await openFilters(); await sizeChip(sizeB).click(); await closeFilters()
    await expectMatches(sizeFiltered([sizeA, sizeB]))
    await openFilters(); await sizeChip(sizeB).click(); assert.equal(await sizeChip(sizeB).getAttribute('aria-pressed'), 'false'); await closeFilters()
    await expectMatches(sizeFiltered([sizeA]))
    // Global search switches to its own filter scope: Beer's facets neither narrow nor are erased by it.
    await search.fill(b1.name)
    const hits = searchHits(b1.name)
    await expectMatches(hits, hits.length)
    assert.ok(await shelf.getByRole('button', { name: 'Remove search filter', exact: true }).isVisible())
    await shelf.scrollIntoViewIfNeeded()
    await page.screenshot({ path: path.join(output, `filtered-shelf-${width}.png`), fullPage: true })
    if (width === 1440) {
      await increase(b1).click(); assert.equal(await quantity(b1).inputValue(), '2')
      await shelf.locator(`[data-product-id="${b1.id}"]`).dragTo(plan)
      assert.equal(await quantity(b1).inputValue(), '3', 'searched native drag still merges a pack')
      await quantity(b1).fill('1')
    }
    await search.fill('')
    await openFilters()
    assert.equal(await brandChip(b1.brand).getAttribute('aria-pressed'), 'true')
    assert.equal(await brandChip(b0.brand).getAttribute('aria-pressed'), 'true')
    assert.equal(await sizeChip(sizeA).getAttribute('aria-pressed'), 'true')
    await closeFilters()
    await expectMatches(sizeFiltered([sizeA]))
    // The other category's filters must neither inherit nor erase Beer's state.
    await chooseCategory(other.category)
    const otherShelf = page.getByRole('region', { name: `${other.category} selection`, exact: true })
    await openFilters()
    assert.equal(await filters.locator('button[aria-pressed="true"]').count(), 0)
    await filters.getByRole('group', { name: 'Brand', exact: true }).getByRole('button').first().click(); await closeFilters()
    await otherShelf.getByRole('button', { name: 'Clear all filters', exact: true }).click() // the other category's own scope
    await search.fill('no such drink')
    await otherShelf.getByRole('button', { name: 'Reset filters', exact: true }).click()
    assert.equal(await search.inputValue(), '')
    await chooseCategory('Beer')
    await openFilters()
    assert.equal(await brandChip(b1.brand).getAttribute('aria-pressed'), 'true')
    assert.equal(await brandChip(b0.brand).getAttribute('aria-pressed'), 'true')
    assert.equal(await sizeChip(sizeA).getAttribute('aria-pressed'), 'true')
    await closeFilters()
    await expectMatches(sizeFiltered([sizeA]))
    await shelf.getByRole('button', { name: 'Clear all filters', exact: true }).click()
    await openFilters(); assert.equal(await filters.locator('button[aria-pressed="true"]').count(), 0); await closeFilters()
    await expectMatches(beer)
    await search.fill('zzzz-no-match')
    await expectMatches([], 0)
    await shelf.getByText('No matching drinks', { exact: true }).waitFor()
    await shelf.scrollIntoViewIfNeeded()
    await page.screenshot({ path: path.join(output, `filter-empty-${width}.png`), fullPage: true })
    if (width === 390) {
      await page.setViewportSize({ width: 320, height: 844 })
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'filter chips wrap at 320')
      await page.screenshot({ path: path.join(output, 'filter-empty-320.png'), fullPage: true })
      await page.setViewportSize({ width, height: 844 })
    }
    await shelf.getByRole('button', { name: 'Reset filters', exact: true }).click()
    await expectMatches(beer)
    assert.equal(await search.inputValue(), '')
    // Search alone also exposes clear-all; reset is not tied to a selected chip.
    await search.fill(b0.name)
    await shelf.getByRole('button', { name: 'Clear all filters', exact: true }).click()
    await expectMatches(beer)
  }
  page.off('request', countFilterRequests)
  assert.equal(filterRequests, 0, 'filtering uses only the already-loaded catalogue')
  await page.setViewportSize({ width: 1440, height: 900 })
  console.log('PASS: shelf brand/size counts, keyboard toggles, facet OR/cross-facet AND, global search scope, category persistence, clear/reset, unchanged inventory, filtered native drag, client-only requests at 1440/390; 320 wrapping')

  // Quantity validation and bounds: raw values are kept, flagged and block review.
  for (const invalid of ['', '0', '1001', '1.5', 'text', '-1', '1e2', ' 2']) {
    await quantity(b0).fill(invalid)
    assert.equal(await quantity(b0).inputValue(), invalid)
    assert.equal(await quantity(b0).getAttribute('aria-invalid'), 'true')
    assert.ok(await increase(b0).isDisabled()); assert.ok(await review().isDisabled())
    assert.match(await line(b0).innerText(), /Enter a whole number from 1 to 1,000/)
  }
  await quantity(b0).fill('999'); await increase(b0).click(); assert.equal(await quantity(b0).inputValue(), '1000')
  assert.ok(await increase(b0).isDisabled(), 'the 1,000-pack maximum disables increase')
  await line(b0).getByRole('button', { name: `Decrease ${b0.name} packs`, exact: true }).click(); assert.equal(await quantity(b0).inputValue(), '999')
  await quantity(b0).fill('2')
  await line(b1).getByRole('button', { name: `Remove ${b1.name}`, exact: true }).click()
  assert.equal(await lines().count(), 1); assert.equal(await quantity(b0).inputValue(), '2')
  await add(b1).focus(); await page.keyboard.press('Enter')
  assert.equal(await quantity(b1).inputValue(), '1')
  const card = page.locator(`[data-product-id="${b1.id}"]`)
  await card.dragTo(plan); assert.equal(await quantity(b1).inputValue(), '2', 'native desktop drag merges one pack')
  const foreign = await page.evaluateHandle(() => { const d = new DataTransfer(); d.setData('text/uri-list', 'https://example.invalid'); d.setData('text/html', '<b>foreign</b>'); return d })
  await plan.dispatchEvent('dragover', { dataTransfer: foreign }); assert.ok(!(await plan.getAttribute('class')).includes('validDrop'))
  await plan.dispatchEvent('drop', { dataTransfer: foreign }); assert.equal(await quantity(b1).inputValue(), '2'); assert.equal(new URL(page.url()).origin, origin)
  const forged = await page.evaluateHandle(id => { const d = new DataTransfer(); d.setData('application/x-allcheers-product', id); return d }, b1.id)
  await plan.dispatchEvent('drop', { dataTransfer: forged }); assert.equal(await quantity(b1).inputValue(), '2', 'tag without an owned drag is ignored')
  await chooseCategory(other.category); await add(other).click()
  await search.fill('no such product')
  assert.equal(await lines().count(), 3, 'search retains inventory')
  const total = b0.pricePaise * 2 + b1.pricePaise * 2 + other.pricePaise
  assert.ok((await plan.innerText()).includes(money(total))); assert.ok(await review().isEnabled())
  await search.fill('')

