// Read-only production UI verification; no live writes or authenticated saves.
const assert = require('node:assert/strict')
const fs = require('node:fs')
const { spawn } = require('node:child_process')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE)
const origin = 'http://127.0.0.1:3142'
async function main() {
  const server = spawn(process.execPath, ['node_modules/next/dist/bin/next','start','--hostname','127.0.0.1','--port','3142'], { stdio: 'ignore' })
  let browser
  try {
    let ready = false
    for(let n=0;n<60;n++){try{await fetch(origin);ready=true;break}catch{await new Promise(r=>setTimeout(r,250))}}
    assert.ok(ready)
    browser = await chromium.launch({ executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE, headless:true })
    fs.mkdirSync('output/playwright/recipe-pantry', { recursive:true })
    const filteredContext = await browser.newContext({viewport:{width:390,height:844}})
    await filteredContext.addCookies([{name:'allcheers_eligible',value:'1',url:origin}])
    const filtered = await filteredContext.newPage()
    await filtered.goto(origin+'/find-my-drink?drink=cocktail&type=vodka&method=build&max=3&q=cranberry', {waitUntil:'networkidle'})
    await filtered.getByRole('button',{name:'Use what I have',exact:true}).click()
    for(const label of ['Vodka','Cranberry Juice','Lime wedge','Ice','Pineapple Juice']) await filtered.getByLabel(label,{exact:true}).check()
    await filtered.locator('#pantry-recipe-dn-bay-breeze').getByRole('link',{name:'Bay Breeze',exact:true}).click()
    await filtered.waitForURL('**/find-my-drink/dn-bay-breeze?*')
    await filtered.getByRole('link',{name:'← Back to recipes',exact:true}).click()
    await filtered.waitForURL('**/find-my-drink?*#pantry-recipe-dn-bay-breeze')
    await filtered.locator('#pantry-recipe-dn-bay-breeze').waitFor()
    const restoredUrl = new URL(filtered.url())
    for(const [key,value] of Object.entries({drink:'cocktail',type:'vodka',method:'build',max:'3',q:'cranberry'})) assert.equal(restoredUrl.searchParams.get(key),value,'pantry detail return preserves '+key)
    const restoredBox=await filtered.locator('#pantry-recipe-dn-bay-breeze').boundingBox()
    assert.ok(restoredBox&&restoredBox.y>=0&&restoredBox.y<844,'filtered pantry origin visible')
    assert.equal(await filtered.getByLabel('Pineapple Juice',{exact:true}).isChecked(),true)
    await filteredContext.close()
    console.log('Pantry filtered detail-return passed: q/drink/type/method/max retained, session selection restored, origin visible at 390px.')
    if(process.argv.includes('--filtered-return-only')) return
    for(const width of [320,390,768,1440]) {
      const context = await browser.newContext({ viewport:{width,height:900} })
      await context.addCookies([{name:'allcheers_eligible',value:'1',url:origin}])
      const page = await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message))
      await page.goto(origin+'/find-my-drink', {waitUntil:'networkidle'})
      await page.getByRole('button',{name:'Use what I have',exact:true}).click()
      await page.getByLabel('Search the ingredient checklist').fill('lime')
      assert.ok(await page.getByLabel('Lime wedge',{exact:true}).isVisible())
      assert.ok(await page.getByLabel('Lime Juice',{exact:true}).isVisible())
      assert.ok(await page.getByLabel('Lime wheel',{exact:true}).isVisible())
      await page.getByLabel('Search the ingredient checklist').fill('')
      for(const label of ['Vodka','Cranberry Juice','Lime wedge','Ice']) await page.getByLabel(label,{exact:true}).check()
      const bay = page.locator('#pantry-recipe-dn-bay-breeze')
      await bay.waitFor()
      assert.match(await bay.innerText(), /Add Pineapple Juice: 2 oz\. Pineapple Juice/)
      assert.match(await bay.innerText(), /Equipment: Highball glass/)
      await page.getByLabel('Pineapple Juice',{exact:true}).check()
      assert.match(await bay.innerText(), /Check every quantity/)
      const ids=await page.locator('[id^="recipe-"],[id^="pantry-recipe-"]').evaluateAll(nodes=>nodes.map(n=>n.id))
      assert.equal(ids.length,new Set(ids).size,'unique recipe DOM anchors')
      const badTargets = await page.locator('button, a, [class*=pantryChecklist] label').evaluateAll(nodes=>nodes.filter(n=>n.closest('[class*="pantry"]')).filter(n=>{const r=n.getBoundingClientRect();return r.width>0&&r.height>0&&r.height<43.9}).map(n=>({text:n.textContent,height:n.getBoundingClientRect().height})))
      assert.deepEqual(badTargets,[],'pantry actionable targets at least 44px')
      assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'no overflow')
      await page.getByLabel('Search the ingredient checklist').focus()
      assert.equal(await page.getByLabel('Search the ingredient checklist').evaluate(n=>document.activeElement===n),true)
      assert.equal(await page.getByLabel('Search the ingredient checklist').evaluate(n=>getComputedStyle(n).outlineStyle),'solid','visible focus outline')
      await page.screenshot({path:`output/playwright/recipe-pantry/focus-${width}.png`,animations:'disabled'})
      await page.locator('img').evaluateAll(async nodes=>{nodes.forEach(n=>n.loading='eager');await Promise.all(nodes.map(n=>Promise.race([n.decode().catch(()=>{}),new Promise(resolve=>setTimeout(resolve,10000))])))})
      await page.screenshot({path:`output/playwright/recipe-pantry/pantry-${width}.png`,fullPage:true,animations:'disabled'})
      await bay.getByRole('link',{name:'Bay Breeze',exact:true}).click()
      await page.waitForURL('**/find-my-drink/dn-bay-breeze?*')
      await page.getByRole('link',{name:'← Back to recipes',exact:true}).click()
      await page.waitForURL('**/find-my-drink#pantry-recipe-dn-bay-breeze')
      await page.locator('#pantry-recipe-dn-bay-breeze').waitFor()
      assert.equal(await page.getByLabel('Pineapple Juice',{exact:true}).isChecked(),true)
      const box=await page.locator('#pantry-recipe-dn-bay-breeze').boundingBox()
      assert.ok(box&&box.y>=0&&box.y<900,'returned pantry origin is visible')
      await page.getByRole('button',{name:'Remove Pineapple Juice',exact:true}).click()
      assert.equal(await page.getByLabel('Pineapple Juice',{exact:true}).isChecked(),false)
      await page.reload({waitUntil:'networkidle'})
      assert.equal(await page.getByLabel('Vodka',{exact:true}).isChecked(),true,'session restored after reload')
      await page.getByRole('link',{name:/^Mocktails \(/}).click()
      await page.waitForURL('**/find-my-drink?drink=mocktail')
      await page.getByRole('heading',{name:'Ingredients I have',exact:true}).waitFor()
      assert.equal(await page.getByLabel('Vodka',{exact:true}).isChecked(),true,'filters retain eligible vocabulary selection')
      assert.equal(await page.locator('#pantry-recipe-dn-bay-breeze').count(),0,'cocktail does not leak under mocktail filter')
      await page.getByRole('button',{name:'Clear ingredients',exact:true}).click()
      assert.equal(await page.getByLabel('Vodka',{exact:true}).isChecked(),false)
      await page.getByRole('link',{name:/^Cocktails \(/}).click()
      await page.waitForURL('**/find-my-drink?drink=cocktail')
      await page.getByLabel('Search by name or ingredient').fill('zzzz-not-a-recipe')
      await page.getByRole('button',{name:'Search',exact:true}).click()
      await page.waitForURL('**/*q=zzzz-not-a-recipe*')
      await page.getByRole('button',{name:'Use what I have',exact:true}).click()
      await page.getByRole('heading',{name:'Ingredients I have',exact:true}).waitFor()
      await page.getByLabel('Vodka',{exact:true}).check()
      await page.getByRole('button',{name:'Clear ingredients',exact:true}).click()
      assert.equal(await page.getByLabel('Vodka',{exact:true}).isChecked(),false,'pantry accessible under zero filter matches')
      assert.deepEqual(errors,[])
      await context.close()
    }
    const blocked=await browser.newContext({viewport:{width:390,height:844}})
    await blocked.addCookies([{name:'allcheers_eligible',value:'1',url:origin}])
    await blocked.addInitScript(()=>{Object.defineProperty(window,'sessionStorage',{get(){throw new Error('blocked')}})})
    const page=await blocked.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message))
    await page.goto(origin+'/find-my-drink#pantry-recipe-%', {waitUntil:'networkidle'})
    await page.getByRole('button',{name:'Use what I have',exact:true}).click()
    await page.getByText('Browser storage is unavailable.',{exact:false}).waitFor()
    await page.getByLabel('Vodka',{exact:true}).check()
    assert.equal(await page.getByLabel('Vodka',{exact:true}).isChecked(),true)
    await page.getByRole('button',{name:'Clear ingredients',exact:true}).click()
    assert.deepEqual(errors,[],'blocked storage/malformed fragment causes no application error')
    await blocked.close()
    const nojs=await browser.newContext({javaScriptEnabled:false,viewport:{width:320,height:844}})
    await nojs.addCookies([{name:'allcheers_eligible',value:'1',url:origin}])
    const ordinary=await nojs.newPage()
    await ordinary.goto(origin+'/find-my-drink?drink=mocktail&q=cola')
    assert.equal(await ordinary.getByRole('button',{name:'Use what I have',exact:true}).count(),0)
    await ordinary.getByRole('link',{name:/Easy Roy Rogers Drink/}).click()
    await ordinary.getByRole('heading',{name:'Ingredients',exact:true}).waitFor()
    assert.ok(await ordinary.getByText('~240 mL cola',{exact:false}).count()>0)
    await nojs.close()
    const gate=await browser.newContext();const g=await gate.newPage();await g.goto(origin+'/find-my-drink')
    assert.equal(await g.getByRole('button',{name:'Use what I have',exact:true}).count(),0,'gate precedes pantry')
    await gate.close()
    console.log('Pantry production browser passed at 320/390/768/1440: exact/one-away, labels/forms, remove/clear, storage restore/blocked, filtered detail-return visible origin, zero matches, no-JS, gate, unique anchors, 44px targets, focus, overflow, zero page errors.')
  } finally { await browser?.close();server.kill() }
}
main().catch(e=>{console.error(e);process.exitCode=1})


