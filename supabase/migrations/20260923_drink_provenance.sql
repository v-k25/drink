-- 20260923_drink_provenance
--
-- Additive provenance/classification columns for the EkQuarter canonical
-- drinks catalogue (public.drinks). Supports the copyright-safe recipe
-- pipeline in scripts/recipe-catalogue/: import rows carry full source
-- provenance (source_name/source_url/source_retrieved_at), a content-origin
-- marker (content_origin) and an alcohol classification (alcohol_type), and
-- stay status='draft' until an owner publishes them.
--
-- Idempotency: every statement is safe to reapply. Columns use ADD COLUMN
-- IF NOT EXISTS; CHECK constraints are created conditionally via
-- pg_constraint lookups (PostgreSQL has no ADD CONSTRAINT IF NOT EXISTS);
-- DROP NOT NULL / SET DEFAULT are naturally idempotent; COMMENT ON
-- overwrites in place.
--
-- Scope guard: no RLS policy, grant, or trigger is changed, and no existing
-- constraint is dropped or altered. The only existing-column change is the
-- sanctioned abv nullability/default below (the 0..100 range check is
-- retained untouched). The public.drinks RLS policies (row level security
-- enabled, owner/site-scoped read) and all grants are left untouched.
--
-- Strictness model: the new columns are nullable with strict value checks,
-- matching the existing schema conventions (cf. serving_temp, status,
-- budget_category, display_name). Manual Studio curation inserts that omit
-- the new columns keep working, while any value that IS present must come
-- from the pipeline's fixed vocabulary. The pre-existing abv range check
-- (drinks_abv_check) is intentionally retained: PostgreSQL CHECK
-- constraints pass when their expression evaluates to NULL, so the
-- 0..100 range still applies to every non-null abv while unknown-ABV rows
-- (sourced from facts, no verified ABV) can store NULL.

alter table public.drinks
  add column if not exists source_name text,
  add column if not exists source_url text,
  add column if not exists source_retrieved_at timestamptz,
  add column if not exists content_origin text,
  add column if not exists alcohol_type text;

-- abv: nullable with default null. The existing abv >= 0 and abv <= 100
-- range check (drinks_abv_check) is retained untouched; NULL passes a CHECK
-- that is not false, so the range still governs every non-null value.
alter table public.drinks alter column abv drop not null;
alter table public.drinks alter column abv set default null;

do $$
begin
  -- Provenance source vocabulary (the two recorded recipe sources).
  if not exists (
    select 1 from pg_constraint
    where conname = 'drinks_source_name_check'
      and conrelid = 'public.drinks'::regclass
  ) then
    alter table public.drinks add constraint drinks_source_name_check
      check (
        source_name is null or source_name = any (
          array['drinknation'::text, 'mindfulmocktail'::text]
        )
      );
  end if;

  -- Source URL: https only, no whitespace, bounded length.
  if not exists (
    select 1 from pg_constraint
    where conname = 'drinks_source_url_check'
      and conrelid = 'public.drinks'::regclass
  ) then
    alter table public.drinks add constraint drinks_source_url_check
      check (
        source_url is null or (
          source_url ~ '^https://[^[:space:]]+$'
          and char_length(source_url) <= 2048
        )
      );
  end if;

  -- Content origin: only AllCheers-owned generated-from-facts wording.
  if not exists (
    select 1 from pg_constraint
    where conname = 'drinks_content_origin_check'
      and conrelid = 'public.drinks'::regclass
  ) then
    alter table public.drinks add constraint drinks_content_origin_check
      check (
        content_origin is null
        or content_origin = 'allcheers_original_from_facts'
      );
  end if;

  -- Alcohol classification vocabulary.
  if not exists (
    select 1 from pg_constraint
    where conname = 'drinks_alcohol_type_check'
      and conrelid = 'public.drinks'::regclass
  ) then
    alter table public.drinks add constraint drinks_alcohol_type_check
      check (
        alcohol_type is null or alcohol_type = any (
          array['cocktail'::text, 'mocktail'::text]
        )
      );
  end if;
end
$$;

comment on column public.drinks.source_name is
  'Recorded source this row''s facts came from: drinknation | mindfulmocktail. NULL for rows with no sourced provenance.';
comment on column public.drinks.source_url is
  'Canonical https URL of the source recipe the facts were taken from. NULL when source_name is NULL.';
comment on column public.drinks.source_retrieved_at is
  'When the source content was retrieved (timestamptz). NULL when source_name is NULL.';
comment on column public.drinks.content_origin is
  'Where the description/preparation wording originated. Only allcheers_original_from_facts is allowed: wording generated by scripts/recipe-catalogue from structured facts, never source prose.';
comment on column public.drinks.alcohol_type is
  'Alcohol classification: cocktail | mocktail. NULL when unclassified.';
